#!/usr/bin/env python3
"""Generate the release checklist from section 15 of the requirements (#182, NFR-23b, AT-22).

  uv run --no-project scripts/gen_release_checklist.py \
      [--requirements research/final-requirements.md] [--out docs/release/RELEASE-CHECKLIST.md]

Every acceptance test whose Gate names a physical device, a live workspace, a release gate or an
MVP exit is a release gate (NFR-23b, D79). Each row has the AT ID, title, gate type and the platforms.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import req_parse  # noqa: E402

HEADER = "Generated by scripts/gen_release_checklist.py. Do not edit by hand."
GATE_RE = re.compile(r"\b(device|live|release|MVP exit)\b")
EXTRA_PLATFORMS = ("Windows 10",)
INSPECTION_PHASES = ("MVP-D", "MVP-M")
# Where the admin inspection steps for an ADM row are written (#20). Other rows use section 10.
INSPECTION_STEPS = {
    "ADM-09": "`docs/admin/model-service-prerequisites.md`",
}


# The local release steps (no Apple Developer Program: the owner signs on the owner's Mac).
RELEASE_STEPS = [
    "", "## Release steps", "",
    "The macOS build is signed on the owner's Mac with the self-signed identity \"Bottle Local Dev "
    "Signing\". The key never leaves that Mac, so no CI job signs for macOS. The Windows installer "
    "is built by `.github/workflows/release.yml` and is unsigned.", "",
    "1. Land the release PR. Check the version in `package.json`, `src-tauri/tauri.conf.json` and "
    "`Cargo.toml`, and write `docs/release/notes-vX.Y.Z.md`.",
    "2. On the Mac, check out `main` at `origin/main` with a clean tree.",
    "3. Run `scripts/release-macos.sh X.Y.Z`. It builds, signs and checks the app, makes the DMG, "
    "signs it and writes the SHA-256 under `dist/release/`.",
    "4. Push the tag `vX.Y.Z`. The Release workflow builds the Windows installer and attaches it to a "
    "draft release.",
    "5. Run the `gh release` command that the script prints. If the draft exists, it is `gh release "
    "upload` for the DMG and the SHA-256 file, then `gh release edit` with `--notes-file` and "
    "`--draft=false`. Otherwise it is `gh release create --verify-tag`.",
    "6. Install the DMG on a clean Mac. Check the Gatekeeper steps in the notes, the permissions and "
    "`codesign -d -r-` (the leaf hash must be unchanged).",
]


def platforms(doc, at):
    text = f"{at.name} {at.procedure} {at.criterion}"
    extra = [p for p in EXTRA_PLATFORMS if p in text]
    return "; ".join([doc.platforms or "reference hardware (section 15)"] + extra)


def build(doc, source):
    gated = [at for at in doc.acceptance_tests.values() if GATE_RE.search(at.gate)]
    counts = {}
    for at in gated:
        for g in GATE_RE.findall(at.gate):
            counts[g] = counts.get(g, 0) + 1
    out = ["# Release checklist", "", HEADER, "",
           f"Source: section 15 of `{source}`. Physical-device and live-workspace tests are release "
           "gates (NFR-23b, D79). AT-22 needs evidence for each gate, and no unrun spike is a pass.", "",
           "Gate types: **device** runs on physical reference hardware; **live** runs against a live "
           "workspace; **release** is a review of the release build; **MVP exit** is an end-to-end MVP gate.", "",
           "| Gate | ATs |", "|---|---|"]
    out += [f"| {g} | {counts[g]} |" for g in ("device", "live", "release", "MVP exit") if g in counts]
    out += ["", "Tick a row only when its evidence (report, log or recording) is linked in the release PR.", "",
            "| Done | AT | Title | Gate | Platforms | Pass criterion | Evidence |",
            "|---|---|---|---|---|---|---|"]
    for at in sorted(gated, key=lambda a: req_parse.id_sort_key(a.id)):
        out.append(f"| [ ] | {at.id} | {at.name} | {at.gate} | {platforms(doc, at)} | {at.criterion} | |")
    out += admin_inspection(doc)
    out += RELEASE_STEPS
    return "\n".join(out) + "\n"


def admin_inspection(doc):
    """The MVP admin prerequisites that section 5.12 verifies by inspection (Verify `I`, #20)."""
    rows = [r for r in doc.requirements.values()
            if r.id.startswith("ADM-") and r.phase in INSPECTION_PHASES and r.verify.startswith("I")]
    if not rows:
        return []
    out = ["", "## Admin inspection", "",
           "These admin prerequisites (section 5.12) are verified by inspection. Inspect each one in "
           "the release workspace and link the evidence in the release PR. Section 10 lists the items.", "",
           "| Done | Req | Requirement | Pass criterion | Steps | Evidence |",
           "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda x: req_parse.id_sort_key(x.id)):
        steps = INSPECTION_STEPS.get(r.id, "Section 10 of the requirements")
        out.append(f"| [ ] | {r.id} | {r.text} | {r.criterion} | {steps} | |")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--requirements", default="research/final-requirements.md")
    ap.add_argument("--out", default="docs/release/RELEASE-CHECKLIST.md")
    args = ap.parse_args(argv)
    with open(args.requirements, encoding="utf-8") as f:
        doc = req_parse.parse(f.read())
    # Forward slashes on every OS, so the committed checklist is the same on Windows.
    source = os.path.relpath(os.path.abspath(args.requirements), os.getcwd()).replace(os.sep, "/")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(build(doc, source))
    for e in doc.errors:
        print(f"ERROR parse: {e}", file=sys.stderr)
    print(f"wrote {args.out}")
    return 1 if doc.errors else 0


if __name__ == "__main__":
    sys.exit(main())
