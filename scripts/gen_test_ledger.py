#!/usr/bin/env python3
"""Generate the test ledger: one row per (test, requirement ID) (#182, NFR-23a).

  uv run --no-project scripts/gen_test_ledger.py --requirements research/final-requirements.md \
      --junit <file.xml>... --out docs/tests/TEST-LEDGER.md [--commit <sha>] \
      [--issues-json <gh issue list json>]

--issues-json takes the output of
`gh issue list --state all --limit 1000 --json number,state,title,body`. Issue = every issue whose
"Requirements to implement" section lists the ID. PR stays blank: it is not derivable from these
inputs, and a blank is better than a guess.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import req_parse  # noqa: E402

HEADER = "Generated by scripts/gen_test_ledger.py. Do not edit by hand."


def issues_by_id(path):
    """Map requirement ID -> sorted issue numbers from a `gh issue list --json` file."""
    if not path:
        return {}
    with open(path, encoding="utf-8") as f:
        issues = json.load(f)
    found = {}
    for issue in issues:
        m = re.search(r"^###\s+Requirements to implement\s*$(.*?)(?=^#{1,3}\s|\Z)",
                      issue.get("body") or "", re.M | re.S)
        if not m:
            continue
        for rid in re.findall(r"`([A-Za-z]+-[A-Za-z]?\d+[a-z]?)`", m.group(1)):
            found.setdefault(rid, set()).add(int(issue["number"]))
    return {k: sorted(v) for k, v in found.items()}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def build(doc, tagged, issues, commit):
    rows = []
    for case, ids in tagged:
        for rid in sorted(ids, key=req_parse.id_sort_key):
            ats = {rid} if rid in doc.acceptance_tests else doc.at_links(rid)
            rows.append((req_parse.id_sort_key(rid), case.label, [
                rid, ", ".join(f"#{n}" for n in issues.get(rid, [])), "", cell(case.label),
                ", ".join(sorted(ats, key=req_parse.id_sort_key)), case.result, commit or ""]))
    rows.sort(key=lambda r: (r[0], r[1]))
    passing = {i for case, ids in tagged if case.result == "passed" for i in ids}

    out = ["# Test ledger", "", HEADER, "",
           "Each row links one test to one requirement or acceptance-test ID (NFR-23a). "
           "See docs/tests/README.md.", "",
           "## Summary", "",
           "Requirement rows with at least one passing test, per milestone.", "",
           "| Milestone | Requirement rows | With passing test |", "|---|---|---|"]
    reqs = doc.requirements
    for phase in req_parse.PHASES:
        ids = [r for r in reqs if reqs[r].phase == phase]
        if ids:
            out.append(f"| {phase} | {len(ids)} | {sum(r in passing for r in ids)} |")
    out.append(f"| Total | {len(reqs)} | {sum(r in passing for r in reqs)} |")
    out += ["", "## Ledger", "",
            "| Requirement ID | Issue | PR | Test (file::name) | AT | Last result | Commit |",
            "|---|---|---|---|---|---|---|"]
    out += ["| " + " | ".join(r[2]) + " |" for r in rows]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--requirements", required=True)
    ap.add_argument("--junit", nargs="*", action="extend", default=[])
    ap.add_argument("--out", required=True)
    ap.add_argument("--commit")
    ap.add_argument("--issues-json")
    args = ap.parse_args(argv)
    with open(args.requirements, encoding="utf-8") as f:
        doc = req_parse.parse(f.read())
    cases, missing, junit_errors = req_parse.read_junit(args.junit)
    tagged, unknown = req_parse.tag_cases(cases, doc.known_ids)
    text = build(doc, tagged, issues_by_id(args.issues_json), args.commit)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    for p in missing:
        print(f"missing JUnit file (not fatal): {p}")
    for k in sorted(unknown):
        print(f"WARN unknown ID {k} (run req_coverage.py for the gate)", file=sys.stderr)
    errors = doc.errors + junit_errors
    for e in errors:
        print(f"ERROR parse: {e}", file=sys.stderr)
    print(f"wrote {args.out}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
