#!/usr/bin/env python3
"""Requirement coverage report (#182, NFR-23a).

Reads the requirements and JUnit XML files, maps each test to the requirement and AT IDs it names,
and writes a markdown report (and optional JSON).

  uv run --no-project scripts/req_coverage.py --requirements research/final-requirements.md \
      --junit <file.xml>... --out reports/requirements-coverage.md \
      [--json reports/requirements-coverage.json] [--strict-must]

Exit 1 when a test names an ID that is not in the requirements, when the requirements or a JUnit
file cannot be parsed, or (only with --strict-must) when a MUST row has no AT link in section 14.3.
Missing JUnit files are reported and are not fatal. Otherwise exit 0.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import req_parse  # noqa: E402


def analyse(requirements_path, junit_paths):
    with open(requirements_path, encoding="utf-8") as f:
        doc = req_parse.parse(f.read())
    cases, missing, junit_errors = req_parse.read_junit(junit_paths)
    tagged, unknown = req_parse.tag_cases(cases, doc.known_ids)
    passing = sorted({i for case, ids in tagged if case.result == "passed" for i in ids},
                     key=req_parse.id_sort_key)
    reqs = doc.requirements
    must = [r for r in reqs if reqs[r].priority == "M"]
    per_phase = {}
    for phase in req_parse.PHASES:
        ids = [r for r in reqs if reqs[r].phase == phase]
        if ids:
            per_phase[phase] = {"rows": len(ids),
                                "must": sum(reqs[r].priority == "M" for r in ids),
                                "with_passing_test": sum(r in passing for r in ids)}
    return {
        "requirements": requirements_path,
        "requirements_total": len(reqs),
        "must_total": len(must),
        "must_ids": must,
        "acceptance_tests_total": len(doc.acceptance_tests),
        "requirements_with_passing_test": sum(r in reqs for r in passing),
        "passing_ids": passing,
        "per_phase": per_phase,
        "tests_total": len(cases),
        "tests_tagged": sum(bool(ids) for _, ids in tagged),
        "unknown_ids": sorted(unknown, key=req_parse.id_sort_key),
        "unknown_tests": {k: unknown[k] for k in sorted(unknown, key=req_parse.id_sort_key)},
        "must_without_at": [r for r in must if not doc.at_links_14_3.get(r)],
        "must_without_verify_at": [r for r in must if not reqs[r].verify_ats],
        "missing_junit": missing,
        "parse_errors": doc.errors + junit_errors,
    }


def render(data):
    out = ["# Requirements coverage", "",
           "Generated by scripts/req_coverage.py. Do not edit by hand.", "",
           f"Source: `{data['requirements']}`", "",
           "## Totals", "",
           "| Measure | Count |", "|---|---|",
           f"| Requirement rows | {data['requirements_total']} |",
           f"| MUST rows | {data['must_total']} |",
           f"| Acceptance tests | {data['acceptance_tests_total']} |",
           f"| Requirement rows with at least one passing test | {data['requirements_with_passing_test']} |",
           f"| Test cases read | {data['tests_total']} |",
           f"| Test cases that name an ID | {data['tests_tagged']} |",
           f"| Unknown IDs | {len(data['unknown_ids'])} |",
           f"| MUST rows without an AT link in 14.3 | {len(data['must_without_at'])} |",
           f"| Parse errors | {len(data['parse_errors'])} |", "",
           "## Per milestone", "",
           "| Milestone | Rows | MUST rows | With passing test |", "|---|---|---|---|"]
    for phase, p in data["per_phase"].items():
        out.append(f"| {phase} | {p['rows']} | {p['must']} | {p['with_passing_test']} |")
    out += ["", "## Unknown IDs", ""]
    if data["unknown_ids"]:
        out += ["These tests name an ID that is not in the requirements.", "",
                "| ID | Tests |", "|---|---|"]
        out += [f"| {k} | {'; '.join(v)} |" for k, v in data["unknown_tests"].items()]
    else:
        out.append("None.")
    out += ["", "## MUST rows without an AT link in section 14.3 (NFR-23a)", ""]
    if data["must_without_at"]:
        out.append(", ".join(data["must_without_at"]))
    else:
        out.append("None.")
    if data["must_without_verify_at"]:
        out += ["", "MUST rows with no AT in the Verify column: " + ", ".join(data["must_without_verify_at"])]
    out += ["", "## IDs with at least one passing test", ""]
    out.append(", ".join(data["passing_ids"]) if data["passing_ids"] else "None.")
    out += ["", "## Missing JUnit files", ""]
    out += [f"- `{p}`" for p in data["missing_junit"]] or ["None."]
    out += ["", "## Parse errors", ""]
    out += [f"- {e}" for e in data["parse_errors"]] or ["None."]
    return "\n".join(out) + "\n"


def write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--requirements", required=True)
    ap.add_argument("--junit", nargs="*", action="extend", default=[])
    ap.add_argument("--out", required=True)
    ap.add_argument("--json")
    ap.add_argument("--strict-must", action="store_true",
                    help="exit 1 when a MUST row has no AT link in section 14.3 (NFR-23a)")
    args = ap.parse_args(argv)
    data = analyse(args.requirements, args.junit)
    write(args.out, render(data))
    if args.json:
        write(args.json, json.dumps(data, indent=2) + "\n")
    print(f"requirements: {data['requirements_total']} rows, {data['must_total']} MUST; "
          f"{data['requirements_with_passing_test']} with a passing test")
    for p in data["missing_junit"]:
        print(f"missing JUnit file (not fatal): {p}")
    failed = False
    for e in data["parse_errors"]:
        print(f"ERROR parse: {e}", file=sys.stderr)
        failed = True
    for k, tests in data["unknown_tests"].items():
        print(f"ERROR unknown ID {k}: {'; '.join(tests)}", file=sys.stderr)
        failed = True
    if data["must_without_at"]:
        level = "ERROR" if args.strict_must else "WARN"
        print(f"{level} NFR-23a: {len(data['must_without_at'])} MUST rows without an AT link in 14.3: "
              + ", ".join(data["must_without_at"]), file=sys.stderr)
        failed = failed or args.strict_must
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
