"""Tests for scripts/gen_release_checklist.py (NFR-23b, AT-22, #182)."""
import re

from conftest import FIXTURES, REAL_REQUIREMENTS, ROOT, run_script

SMALL = FIXTURES / "requirements_small.md"
HEADER = "Generated by scripts/gen_release_checklist.py. Do not edit by hand."


def _checklist(tmp_path, requirements):
    out = tmp_path / "CHECKLIST.md"
    proc = run_script("gen_release_checklist.py", "--requirements", requirements, "--out", out)
    return proc, out.read_text() if out.exists() else ""


def _rows(text):
    return {m.group(1): line for line in text.splitlines()
            if (m := re.match(r"^\| \[ \] \| (AT-\d+) \|", line))}


def test_nfr_23b_checklist_lists_device_live_and_release_ats(tmp_path):
    """[NFR-23b] [AT-22] Device, live, release and MVP-exit ATs are all release gates."""
    proc, text = _checklist(tmp_path, SMALL)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert HEADER in text
    rows = _rows(text)
    assert set(rows) == {"AT-01", "AT-02", "AT-22", "AT-31"}
    assert "| device |" in rows["AT-01"]
    assert "| live |" in rows["AT-02"]
    assert "| release |" in rows["AT-22"]
    assert "| MVP exit, live |" in rows["AT-31"]
    assert "MVP-D end to end" in rows["AT-31"] and "**" not in rows["AT-31"]


def test_nfr_23b_checklist_shows_platforms(tmp_path):
    """[NFR-23b] Each row names the reference platforms from section 15."""
    proc, text = _checklist(tmp_path, SMALL)
    row = _rows(text)["AT-01"]
    assert "macOS 14.4" in row and "Windows 11" in row


def test_at_22_real_checklist_covers_every_gated_at(tmp_path):
    """[AT-22] [NFR-23b] On the real file every AT whose gate is device, live, release or MVP exit is listed."""
    proc, text = _checklist(tmp_path, REAL_REQUIREMENTS)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    src = REAL_REQUIREMENTS.read_text()
    section = src[src.index("## 15. Acceptance tests"):src.index("## 16.")]
    expected = set()
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if re.fullmatch(r"AT-\d+", cells[0]) and re.search(r"device|live|release|MVP exit", cells[-1]):
            expected.add(cells[0])
    assert len(expected) >= 40
    assert set(_rows(text)) == expected
    for at in ("AT-22", "AT-31", "AT-32", "AT-37"):
        assert at in _rows(text)


def test_nfr_23b_committed_checklist_matches_generator(tmp_path):
    """[NFR-23b] docs/release/RELEASE-CHECKLIST.md equals the generator output."""
    proc, text = _checklist(tmp_path, REAL_REQUIREMENTS)
    committed = ROOT / "docs" / "release" / "RELEASE-CHECKLIST.md"
    assert committed.exists()
    assert committed.read_text() == text


def _admin_rows(text):
    return {m.group(1): line for line in text.splitlines()
            if (m := re.match(r"^\| \[ \] \| (ADM-\d+[a-z]?) \|", line))}


def test_adm_09_checklist_lists_admin_inspection_rows(tmp_path):
    """[ADM-09] [AT-22] The checklist has an admin inspection step for each MVP ADM row verified by inspection."""
    proc, text = _checklist(tmp_path, REAL_REQUIREMENTS)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "## Admin inspection" in text
    rows = _admin_rows(text)
    assert "ADM-09" in rows
    assert "inference tables" in rows["ADM-09"].lower()
    assert "docs/admin/model-service-prerequisites.md" in rows["ADM-09"]
    src = REAL_REQUIREMENTS.read_text()
    expected = set()
    for line in src.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if (len(cells) == 8 and re.fullmatch(r"ADM-\d+[a-z]?", cells[0])
                and cells[2] in ("MVP-D", "MVP-M") and cells[5].startswith("I")):
            expected.add(cells[0])
    assert expected and set(rows) == expected
    # A row verified by a test (T) is not an inspection step.
    assert "ADM-04a" not in rows


def test_adm_09_admin_doc_covers_model_service_prerequisites():
    """[ADM-04a] [ADM-04b] [ADM-09] The admin doc names each model service, cross-geo routing and inference tables."""
    doc = ROOT / "docs" / "admin" / "model-service-prerequisites.md"
    assert doc.exists()
    text = doc.read_text()
    for rid in ("ADM-04a", "ADM-04b", "ADM-09"):
        assert rid in text
    for service in ("ASR", "cleanup", "router", "writer", "judge", "embedding", "main agent"):
        assert service in text
    assert "SttPolicy=local_only" in text
    assert "cross-geography routing" in text.lower()
    # ADM-09: the exact config field and its pass value, inside the ADM-09 section.
    adm09 = text[text.index("(ADM-09)"):]
    assert "`ai_gateway.inference_table_config.enabled` must be `false` or absent" in adm09
    assert "--profile <your-profile>" in text
    # Checklist item 5: the service tags.
    assert "`app=bottle,stage=<x>`" in text
    # The system.ai.* grant is not verified yet; the page links the human step on #20.
    assert "not verified" in text
    assert "issues/20#issuecomment-6966537505" in text


def test_adm_04a_admin_doc_says_the_check_is_not_wired_yet():
    """[ADM-04a] The admin doc does not claim that the access check runs before #19 and #52 wire it."""
    text = (ROOT / "docs" / "admin" / "model-service-prerequisites.md").read_text()
    section = text[text.index("## What Bottle does when a prerequisite is missing"):]
    assert "Bottle checks each service on the home profile" not in section
    assert "#19" in section and "#52" in section
    assert "not run yet" in section


def test_release_steps_section_lists_local_signing_flow(tmp_path):
    """[NFR-23b] The checklist ends with the release steps: local macOS script, tag, gh release."""
    proc, text = _checklist(tmp_path, SMALL)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    section = text[text.index("## Release steps"):]
