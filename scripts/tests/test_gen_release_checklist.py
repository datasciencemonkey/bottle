"""Tests for scripts/gen_release_checklist.py (NFR-23b, AT-22, #182)."""
import re

from conftest import FIXTURES, REAL_REQUIREMENTS, ROOT, run_script

SMALL = FIXTURES / "requirements_small.md"
HEADER = "Generated by scripts/gen_release_checklist.py. Do not edit by hand."


def _checklist(tmp_path, requirements):
    out = tmp_path / "CHECKLIST.md"
    proc = run_script("gen_release_checklist.py", "--requirements", requirements, "--out", out)
    return proc, out.read_text() if out.exists() else ""


def _rows(text):
    return {m.group(1): line for line in text.splitlines()
            if (m := re.match(r"^\| \[ \] \| (AT-\d+) \|", line))}


def test_nfr_23b_checklist_lists_device_live_and_release_ats(tmp_path):
    """[NFR-23b] [AT-22] Device, live, release and MVP-exit ATs are all release gates."""
    proc, text = _checklist(tmp_path, SMALL)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert HEADER in text
    rows = _rows(text)
    assert set(rows) == {"AT-01", "AT-02", "AT-22", "AT-31"}
    assert "| device |" in rows["AT-01"]
    assert "| live |" in rows["AT-02"]
    assert "| release |" in rows["AT-22"]
    assert "| MVP exit, live |" in rows["AT-31"]
    assert "MVP-D end to end" in rows["AT-31"] and "**" not in rows["AT-31"]


def test_nfr_23b_checklist_shows_platforms(tmp_path):
    """[NFR-23b] Each row names the reference platforms from section 15."""
    proc, text = _checklist(tmp_path, SMALL)
    row = _rows(text)["AT-01"]
    assert "macOS 14.4" in row and "Windows 11" in row


def test_at_22_real_checklist_covers_every_gated_at(tmp_path):
    """[AT-22] [NFR-23b] On the real file every AT whose gate is device, live, release or MVP exit is listed."""
    proc, text = _checklist(tmp_path, REAL_REQUIREMENTS)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    src = REAL_REQUIREMENTS.read_text()
    section = src[src.index("## 15. Acceptance tests"):src.index("## 16.")]
    expected = set()
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if re.fullmatch(r"AT-\d+", cells[0]) and re.search(r"device|live|release|MVP exit", cells[-1]):
            expected.add(cells[0])
    assert len(expected) >= 40
    assert set(_rows(text)) == expected
    for at in ("AT-22", "AT-31", "AT-32", "AT-37"):
        assert at in _rows(text)


def test_nfr_23b_committed_checklist_matches_generator(tmp_path):
    """[NFR-23b] docs/release/RELEASE-CHECKLIST.md equals the generator output."""
    proc, text = _checklist(tmp_path, REAL_REQUIREMENTS)
    committed = ROOT / "docs" / "release" / "RELEASE-CHECKLIST.md"
    assert committed.exists()
    assert committed.read_text() == text
