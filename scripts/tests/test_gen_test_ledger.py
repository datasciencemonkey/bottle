"""Tests for scripts/gen_test_ledger.py (NFR-23a, #182)."""
from conftest import FIXTURES, REAL_REQUIREMENTS, ROOT, run_script

SMALL = FIXTURES / "requirements_small.md"
MIXED = FIXTURES / "junit_mixed.xml"
HEADER = "Generated by scripts/gen_test_ledger.py. Do not edit by hand."


def _ledger(tmp_path, *args):
    out = tmp_path / "LEDGER.md"
    proc = run_script("gen_test_ledger.py", "--requirements", SMALL, "--out", out, *args)
    return proc, out.read_text() if out.exists() else ""


def test_nfr_23a_ledger_has_header_and_columns(tmp_path):
    """[NFR-23a] The ledger names its generator and has the seven columns."""
    proc, text = _ledger(tmp_path, "--junit", MIXED)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert HEADER in text
    assert "| Requirement ID | Issue | PR | Test (file::name) | AT | Last result | Commit |" in text


def test_nfr_23a_ledger_one_row_per_test_and_id(tmp_path):
    """[NFR-23a] A test with two IDs makes two rows; results and ATs show per row."""
    proc, text = _ledger(tmp_path, "--junit", MIXED, "--commit", "abc1234")
    rows = [r for r in text.splitlines() if r.startswith("| ") and "rejects a token-like key" in r]
    assert len(rows) == 2
    assert any(r.startswith("| MB-02 |") and "| AT-02 |" in r and "| passed |" in r for r in rows)
    assert any(r.startswith("| AT-02 |") for r in rows)
    failed = [r for r in text.splitlines() if "cap_14a_stops_on_esc" in r]
    assert len(failed) == 1 and "| failed |" in failed[0] and "| AT-01 |" in failed[0]
    assert "| abc1234 |" in failed[0]
    hub = [r for r in text.splitlines() if "test_mb_01_creates_mogs" in r][0]
    assert "scripts/tests/test_hub.py::test_mb_01_creates_mogs" in hub


def test_nfr_23a_ledger_issue_from_issues_json(tmp_path):
    """[NFR-23a] Issue comes only from "Requirements to implement"; PR stays blank."""
    proc, text = _ledger(tmp_path, "--junit", MIXED, "--issues-json", FIXTURES / "issues.json")
    assert proc.returncode == 0, proc.stdout + proc.stderr
    mb01 = [r for r in text.splitlines() if r.startswith("| MB-01 |")][0]
    cells = [c.strip() for c in mb01.strip("|").split("|")]
    assert cells[1] == "#11, #12" and cells[2] == ""
    cap14a = [r for r in text.splitlines() if r.startswith("| CAP-14a |")][0]
    assert [c.strip() for c in cap14a.strip("|").split("|")][1] == "#12"


def test_nfr_23a_ledger_summary_per_milestone(tmp_path):
    """[NFR-23a] The summary counts requirement IDs with a passing test per milestone."""
    proc, text = _ledger(tmp_path, "--junit", MIXED)
    assert "| MVP-D | 5 | 3 |" in text
    assert "| MVP-M | 1 | 1 |" in text
    assert "| v1 | 2 | 0 |" in text
    assert "| Total | 8 | 4 |" in text


def test_nfr_23a_ledger_without_junit_is_empty_with_totals(tmp_path):
    """[NFR-23a] With no JUnit files the table is empty and the totals show."""
    proc, text = _ledger(tmp_path)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "| Total | 8 | 0 |" in text
    assert not [r for r in text.splitlines() if r.startswith("| MB-")]


def test_nfr_23a_committed_ledger_matches_generator(tmp_path):
    """[NFR-23a] docs/tests/TEST-LEDGER.md equals the generator output with no JUnit files."""
    out = tmp_path / "LEDGER.md"
    proc = run_script("gen_test_ledger.py", "--requirements", REAL_REQUIREMENTS, "--out", out)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    committed = ROOT / "docs" / "tests" / "TEST-LEDGER.md"
    assert committed.exists()
    assert committed.read_text() == out.read_text()
